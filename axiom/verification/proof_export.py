"""Export kernel proofs to Lean 4 (Mathlib).

Coverage is partial and honest: rules without a translation are emitted
with `sorry`, and anything containing `sorry` is never marked VERIFIED.
"""
from __future__ import annotations

from typing import Optional

import sympy as sp

from ..kernel.expressions import (Add, Const, Div, Expr, Mul, Pow, Sub, Sum, Var)
from ..kernel.proof_objects import Proof
from ..kernel.propositions import Divides, Eq, ForAll, Le, Lt, strip_forall


def lean_expr(e: Expr, cast: str = "") -> str:
    if isinstance(e, Var):
        return f"({e.name} : {cast})" if cast else e.name
    if isinstance(e, Const):
        v = e.value
        s = str(v.numerator) if v.denominator == 1 else f"({v.numerator} / {v.denominator})"
        return f"({s} : {cast})" if cast else s
    if isinstance(e, Add):
        return f"({lean_expr(e.a, cast)} + {lean_expr(e.b, cast)})"
    if isinstance(e, Sub):
        return f"({lean_expr(e.a, cast)} - {lean_expr(e.b, cast)})"
    if isinstance(e, Mul):
        return f"({lean_expr(e.a, cast)} * {lean_expr(e.b, cast)})"
    if isinstance(e, Div):
        return f"({lean_expr(e.a, cast)} / {lean_expr(e.b, cast)})"
    if isinstance(e, Pow):
        return f"({lean_expr(e.base, cast)} ^ {lean_expr(e.exp)})"
    if isinstance(e, Sum):
        return (f"(∑ {e.index.name} ∈ Finset.Icc {lean_expr(e.lo)} {lean_expr(e.hi)}, "
                f"{lean_expr(e.body, cast)})")
    raise ValueError(f"no Lean translation for {type(e).__name__}")


def export_theorem(proof: Proof, name: str) -> Optional[str]:
    c = proof.conclusion
    binders, body = strip_forall(c)
    try:
        if proof.rule == "residue_divisibility":
            n = binders[0][0].name
            d = int(body.d.value)
            f = lean_expr(body.e)
            return (f"theorem {name} ({n} : ℤ) : ({d} : ℤ) ∣ {f} := by\n"
                    f"  have key : ∀ m : ZMod {d}, {lean_expr(body.e).replace(n, 'm')} = 0 := by decide\n"
                    f"  have h := key ({n} : ZMod {d})\n"
                    f"  exact (ZMod.intCast_zmod_eq_zero_iff_dvd _ {d}).1 (by push_cast; exact h)\n")
        if proof.rule == "algebraic_identity" and all(isinstance(x, Var) for x, _ in binders):
            vs = " ".join(v.name for v, _ in binders)
            hdr = f"({vs} : ℚ) " if vs else ""
            return (f"theorem {name} {hdr}: {lean_expr(body.lhs)} = {lean_expr(body.rhs)} := by\n"
                    f"  ring\n")
        if proof.rule == "sum_induction" and binders[0][1] == 0:
            n = binders[0][0].name
            lhs = lean_expr(body.lhs, "ℚ").replace(f"({n} : ℚ)", n)
            lhs = lhs.replace(f"Finset.Icc {lean_expr(body.lhs.lo)} {n}", f"Finset.Icc {lean_expr(body.lhs.lo)} {n}")
            rhs = lean_expr(body.rhs, "ℚ")
            return (f"theorem {name} ({n} : ℕ) : {lhs} = {rhs} := by\n"
                    f"  induction {n} with\n"
                    f"  | zero => simp\n"
                    f"  | succ k ih =>\n"
                    f"    rw [Finset.sum_Icc_succ_top (by omega), ih]\n"
                    f"    push_cast\n"
                    f"    ring\n")
        if proof.rule == "shift_nonneg":
            n, L = binders[0]
            rel = "≤" if isinstance(body, Le) else "<"
            return (f"theorem {name} ({n.name} : ℤ) (h : {L} ≤ {n.name}) : "
                    f"{lean_expr(body.lhs)} {rel} {lean_expr(body.rhs)} := by\n"
                    f"  obtain ⟨m, hm, rfl⟩ : ∃ m, 0 ≤ m ∧ {n.name} = m + {L} := ⟨{n.name} - {L}, by omega, by ring⟩\n"
                    f"  nlinarith [sq_nonneg m, mul_nonneg hm (sq_nonneg m), pow_nonneg hm 3, pow_nonneg hm 4]\n")
    except Exception:
        return None
    return None


def export_file(proofs, header_comment: str = ""):
    """Return (lean_source, exported_proofs, skipped_proofs).
    Proofs without a translation are listed in comments only, so the file
    never contains `sorry`."""
    lines = ["import Mathlib", "", "/-! Generated by AXIOM. " + header_comment + " -/", ""]
    exported, skipped = [], []
    for idx, p in enumerate(proofs):
        name = f"axiom_result_{idx + 1}"
        body = export_theorem(p, name)
        if body is None:
            skipped.append(p)
            lines.append(f"-- not exported (no Lean translation for rule '{p.rule}' yet): {p.conclusion}")
            continue
        exported.append(p)
        lines.append(f"-- kernel rule: {p.rule}")
        lines.append(f"-- statement: {p.conclusion}")
        lines.append(body)
    return "\n".join(lines), exported, skipped
